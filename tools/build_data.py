"""Assemble app/js/data.js (countries, option rules, clue bank) and app/credits.html.

Run after build_flags.py, build_maps.py, fetch_anthems.py and make_language_clips.py.
Song start points live in song_starts.json so the team can tune them by ear.
"""
import html
import json
from pathlib import Path

from countries import COUNTRIES, FLAG_LOOKALIKES, LANGUAGE_CLIPS, SIMILAR_LANGS

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
BUILD = ROOT / "tools" / "build"
SONG_STARTS = ROOT / "tools" / "song_starts.json"
SONG_SECONDS = 15


def load_json(path, default):
    return json.loads(path.read_text(encoding="utf8")) if path.exists() else default


def main():
    maps_js =(APP / "js" / "maps.js").read_text(encoding="utf8")
    shapes_json = maps_js.split("window.SHAPES = ", 1)[1].rstrip().rstrip(";")
    shapes = set(json.loads(shapes_json))

    anthems = load_json(BUILD / "anthem_manifest.json", {})
    starts = load_json(SONG_STARTS, {})
    langs = load_json(BUILD / "language_manifest.json", {})

    countries = {c["code"]: {k: c[k] for k in ("name", "ja", "cont", "langs", "tier", "fact")} for c in COUNTRIES}
    clues = []
    for c in COUNTRIES:
        code, easy = c["code"], c["tier"] == 1
        clues.append({"id": f"flag-{code}", "seg": "flag", "c": code, "diff": "easy" if easy else "medium",
                      "src": f"assets/flags/{code}.svg"})
        if c.get("crop"):
            clues.append({"id": f"flagzoom-{code}", "seg": "flag", "c": code, "diff": "medium",
                          "src": f"assets/flags/{code}.svg", "crop": list(c["crop"])})
        if not c.get("nomap"):
            clues.append({"id": f"locate-{code}", "seg": "map", "c": code, "diff": "easy", "mode": "locate"})
        if code in shapes:
            clues.append({"id": f"shape-{code}", "seg": "map", "c": code, "diff": "medium", "mode": "shape"})
        if (APP / "assets" / "audio" / "anthems" / f"{code}.mp3").exists():
            clues.append({"id": f"song-{code}", "seg": "song", "c": code, "diff": "easy" if easy else "medium",
                          "src": f"assets/audio/anthems/{code}.mp3", "start": starts.get(code, 0),
                          "dur": SONG_SECONDS})

    for clip_id, _locale, country, lang, _text in LANGUAGE_CLIPS:
        clues.append({"id": f"lang-{clip_id}", "seg": "lang", "c": country, "diff": "medium",
                      "src": f"assets/audio/language/{clip_id}.mp3", "lang": lang})

    data = {
        "countries": countries,
        "flagLookalikes": [sorted(g) for g in FLAG_LOOKALIKES],
        "similarLangs": [sorted(g) for g in SIMILAR_LANGS],
        "clues": clues,
    }
    js = ("// Generated by tools/build_data.py. Edit tools/countries.py and rebuild instead.\n"
          f"window.DATA = {json.dumps(data, ensure_ascii=False, indent=1)};\n")
    (APP / "js" / "data.js").write_text(js, encoding="utf8")

    counts = {}
    for cl in clues:
        counts[cl["seg"]] = counts.get(cl["seg"], 0) + 1
    print("clues per segment:", counts)
    write_credits(anthems, langs)


def write_credits(anthems, langs):
    rows = "".join(
        f"<tr><td>{html.escape(m['title'])}</td><td>{html.escape(m['artist'] or 'United States Navy Band')}</td>"
        f"<td>{html.escape(m['license'])}</td><td><a href=\"{html.escape(m['page'])}\">source</a></td></tr>"
        for m in anthems.values())
    voices = sorted({m["voice"] for m in langs.values()})
    page = f"""<!doctype html><meta charset="utf-8"><title>Credits — Spin the Globe</title>
<style>body{{font:15px/1.5 -apple-system,system-ui,sans-serif;max-width:900px;margin:2em auto;padding:0 1em}}
td,th{{border-bottom:1px solid #ddd;padding:4px 8px;text-align:left}}table{{border-collapse:collapse}}</style>
<h1>Credits</h1>
<h2>Flags</h2><p>flag-icons by Panayiotis Lipiridis and contributors, MIT licence (assets/flags/LICENSE-flag-icons.txt).</p>
<h2>Maps</h2><p>Natural Earth 1:50m Admin 0 countries, public domain (naturalearthdata.com).</p>
<h2>National anthems</h2><p>Instrumental recordings by the United States Navy Band, via Wikimedia Commons.</p>
<table><tr><th>File</th><th>Performer</th><th>Licence</th><th></th></tr>{rows}</table>
<h2>Language clips</h2><p>Synthesized speech: {html.escape(', '.join(voices))}.</p>
"""
    (APP / "credits.html").write_text(page, encoding="utf8")


if __name__ == "__main__":
    main()
