"""Generate the offline files for the hosted version.

Writes app/js/version.js (build stamp the page reads) and app/sw.js (service
worker that caches every file). Run after build_data.py, before publishing.
"""
import hashlib
import json
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
GENERATED = {"sw.js", "js/version.js"}

# Bump on every publish. The title screen shows it beside the build stamp.
RELEASE = "1.2.5"

SW = r"""// Generated by tools/build_site.py. Caches every file so the quiz runs offline.

const VERSION = "__VERSION__";
const CACHE = "stg-" + VERSION;
const FILES = __FILES__;

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const queue = FILES.slice();
    const worker = async () => {
      for (let url = queue.shift(); url; url = queue.shift()) {
        if (await cache.match(url)) continue;
        const res = await fetch(url, { cache: "no-cache" });
        if (!res.ok) throw new Error(url + " " + res.status);
        await cache.put(url, res);
      }
    };
    await Promise.all([worker(), worker(), worker(), worker()]);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith("stg-") && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

// Safari asks for audio in byte ranges and rejects a full response, so slice it here.
async function rangeResponse(request, response) {
  const buf = await response.arrayBuffer();
  const m = /bytes=(\d*)-(\d*)/.exec(request.headers.get("range") || "");
  const size = buf.byteLength;
  let start = m && m[1] ? Number(m[1]) : 0;
  let end = m && m[2] ? Number(m[2]) : size - 1;
  if (m && !m[1] && m[2]) { start = size - Number(m[2]); end = size - 1; }
  end = Math.min(end, size - 1);
  return new Response(buf.slice(start, end + 1), {
    status: 206,
    headers: {
      "Content-Type": response.headers.get("Content-Type") || "audio/mpeg",
      "Content-Range": `bytes ${start}-${end}/${size}`,
      "Content-Length": String(end - start + 1),
      "Accept-Ranges": "bytes",
    },
  });
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(request, { ignoreSearch: true });
    if (!cached) {
      try { return await fetch(request); } catch (e) { return new Response("", { status: 504 }); }
    }
    return request.headers.has("range") ? rangeResponse(request, cached) : cached;
  })());
});
"""


def main():
    files = sorted(p for p in APP.rglob("*") if p.is_file())
    rel = [p.relative_to(APP).as_posix() for p in files]
    digest = hashlib.sha256(RELEASE.encode())
    for p, r in zip(files, rel):
        if r not in GENERATED:
            digest.update(r.encode())
            digest.update(p.read_bytes())
    version = digest.hexdigest()[:10]

    urls = ["./"] + [urllib.parse.quote(r) for r in rel if r != "sw.js"]
    if "js/version.js" not in rel:
        urls.append("js/version.js")
    (APP / "js" / "version.js").write_text(
        "// Generated by tools/build_site.py.\n"
        f"self.BUILD = {json.dumps({'release': RELEASE, 'version': version, 'files': len(urls)})};\n", encoding="utf8")
    (APP / "sw.js").write_text(SW.replace("__VERSION__", version).replace("__FILES__", json.dumps(urls, indent=1)),
                               encoding="utf8")
    print(f"version {version} · {len(urls)} files cached offline")


if __name__ == "__main__":
    main()
